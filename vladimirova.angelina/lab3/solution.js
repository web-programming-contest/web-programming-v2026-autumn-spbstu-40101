/**
 * Объединяет два массива, удаляя дубликаты.
 * Порядок: сначала элементы первого массива, затем новые элементы второго.
 * Входные массивы не изменяются.
 * @param {Array} arr1 - первый массив
 * @param {Array} arr2 - второй массив
 * @returns {Array} новый массив уникальных элементов
 */
export function mergeArrays(arr1, arr2) {
  return [...new Set([...arr1, ...arr2])];
}
